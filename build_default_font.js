// Test text render
function renderTest(str) {
  const lines = Array(15).fill('');
  for (let r = 0; r < 15; r++) {
    const row = [];
    for (const c of str) {
      const g = font[c] || font['?'];
      row.push(g.rows[r]);
    }
    lines[r] = row.join(' ');
  }
  return lines.join('\n');
}

