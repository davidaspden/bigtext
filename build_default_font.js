// Comprehensive Font Matrix Generator for 15-Row Block Font
// Produces 15-row tall glyphs with width up to 5 blocks across.
// Includes uppercase A-Z, lowercase a-z, digits 0-9, symbols !£$%&@#/?. and more!

const fs = require('fs');

const font = {};

// Helper to define a glyph
function addGlyph(char, width, lines) {
  if (lines.length !== 15) {
    throw new Error(`Char '${char}' has ${lines.length} lines instead of 15!`);
  }
  const cleanLines = lines.map(line => {
    let s = line.replace(/S/g, '█').replace(/D/g, '▓').replace(/M/g, '▒').replace(/L/g, '░');
    if (s.length < width) s = s.padEnd(width, ' ');
    if (s.length > width) s = s.substring(0, width);
    return s;
  });
  font[char] = {
    width: width,
    rows: cleanLines
  };
}

